/**
 * Writes src/lib/dict/client-keys.ts: the dictionary keys that client components ("use client") use.
 * The server sends only these phrases (active language only) to the browser, keeping pages light.
 * Runs before every build (npm "prebuild"); evals fail if the file is stale or a client key is unknown.
 *   npx tsx scripts/client-keys.ts          write the file
 *   import { collectClientKeys } from ...   used by evals
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DICT } from "../src/lib/i18n";

const ROOT = join(__dirname, "..", "src");
export const OUT = join(ROOT, "lib", "dict", "client-keys.ts");

function walk(dir: string, out: string[] = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx|ts)$/.test(f)) out.push(p);
  }
  return out;
}

/** Client files, plus files they import that render text without "use client" of their own are covered by the server. */
export function collectClientKeys() {
  const keys = new Set<string>();
  const prefixes = new Set<string>();
  const unknown: string[] = [];
  for (const file of walk(ROOT)) {
    const src = readFileSync(file, "utf8");
    if (!/^\s*["']use client["']/.test(src)) continue;
    for (const m of src.matchAll(/["']([a-z_]+(?:\.[a-zA-Z0-9_]+)+)["']/g)) {
      if (DICT[m[1]]) keys.add(m[1]);
      else if (/\btr?\(\s*["']/.test(src.slice(Math.max(0, m.index! - 7), m.index! + 1))) unknown.push(`${file.replace(ROOT, "src")}: ${m[1]}`);
    }
    for (const m of src.matchAll(/`([a-z_]+(?:\.[a-zA-Z0-9_]+)*\.)\$\{/g)) prefixes.add(m[1]);
  }
  for (const p of prefixes) for (const k of Object.keys(DICT)) if (k.startsWith(p)) keys.add(k);
  // Legacy keys have no dot (e.g. "in_stock") and are easy to miss when called through a renamed helper
  // such as tr("in_stock"); there are only a few, so always send them.
  for (const k of Object.keys(DICT)) if (!k.includes(".")) keys.add(k);
  return { keys: [...keys].sort(), prefixes: [...prefixes].sort(), unknown };
}

export function render(keys: string[]) {
  return `// Generated by scripts/client-keys.ts (runs before every build). Do not edit by hand.\n// Dictionary keys used by client components; only these phrases are sent to the browser.\nexport const CLIENT_KEYS: readonly string[] = ${JSON.stringify(keys, null, 2)};\n`;
}

if (process.argv[1] && /client-keys\.ts$/.test(process.argv[1])) {
  const { keys, unknown } = collectClientKeys();
  writeFileSync(OUT, render(keys));
  console.log(`client keys: ${keys.length} written${unknown.length ? `; unknown keys: ${unknown.join(", ")}` : ""}`);
}
